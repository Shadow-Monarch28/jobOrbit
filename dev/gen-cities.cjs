// Builds src/lib/data/cities.js from the all-the-cities dataset (GeoNames).
//   npm i --no-save all-the-cities && node dev/gen-cities.cjs
// Keeps every capital, every city of 100,000+ people, India's cities of 30,000+,
// and each country's three biggest cities so small countries are not empty.
const fs = require('fs')
const cities = require('all-the-cities')
const names = new Intl.DisplayNames(['en'], { type: 'region' })
const FIX = {
  Czechia: 'Czech Republic', 'Côte d’Ivoire': 'Ivory Coast', Türkiye: 'Turkey', 'Myanmar (Burma)': 'Myanmar',
  'Congo - Kinshasa': 'Democratic Republic of the Congo', 'Congo - Brazzaville': 'Congo', 'Cape Verde': 'Cabo Verde',
  'Palestinian Territories': 'Palestine', 'Hong Kong SAR China': 'Hong Kong', 'Macao SAR China': 'Macao', 'St. Vincent and Grenadines': 'Saint Vincent and the Grenadines', 'São Tomé and Príncipe': 'Sao Tome and Principe', 'Saint Vincent and Grenadines': 'Saint Vincent and the Grenadines',
  'Micronesia (Federated States of)': 'Micronesia', 'Vatican City': 'Vatican City', 'Eswatini': 'Eswatini',
}
const country = (cc) => { const n = names.of(cc) || cc; return FIX[n] || n.replace(/&/g, 'and').replace(/\bSt\./g, 'Saint') }
const by = new Map()
for (const c of cities) {
  if (!by.has(c.country)) by.set(c.country, [])
  by.get(c.country).push(c)
}
const out = []
for (const [cc, list] of by) {
  list.sort((a, b) => b.population - a.population)
  const keep = new Set()
  list.slice(0, 3).forEach((c) => keep.add(c))
  for (const c of list) {
    if (c.featureCode === 'PPLC' || c.population >= 100000 || (cc === 'IN' && c.population >= 30000)) keep.add(c)
  }
  const seen = new Set()
  for (const c of [...keep].sort((a, b) => b.population - a.population)) {
    const label = `${c.name}, ${country(cc)}`
    if (seen.has(label)) continue
    seen.add(label)
    out.push([label, c.population])
  }
}
out.sort((a, b) => b[1] - a[1])
const body = out.map(([l]) => JSON.stringify(l)).join(',\n  ')
fs.writeFileSync(__dirname + '/../src/lib/data/cities.js', `// Generated by dev/gen-cities.cjs from the GeoNames-based all-the-cities dataset. Do not edit by hand.
// ${out.length} cities, biggest first, as "City, Country". Any other city can still be typed in.
export const CITY_SUGGESTIONS = [
  ${body},
]
`)
